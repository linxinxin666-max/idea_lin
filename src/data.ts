export function generateContent(
  personaId: string,
  contentTypeId: string
): { text: string; tags: string[] } {
  const personaTemplates = TEMPLATES[personaId as keyof typeof TEMPLATES];
  const templates = personaTemplates[contentTypeId as keyof typeof personaTemplates];
  const randomIndex = Math.floor(Math.random() * templates.length);
  const text = templates[randomIndex];
  const tagsMatch = text.match(/#[^\s#]+/g);
  const tags = tagsMatch || [];
  return { text, tags };
}
